import { describe, expect, it } from "vitest";
import { parseRubAmounts } from "../src/domain/parse-rub-amounts.js";
const values = (text: string) =>
  parseRubAmounts(text).map((a) => a.rubles.toString());
describe("RUB parser", () => {
  it.each([
    ["Купил за 1000 рублей", ["1000"]],
    ["100 ₽ и 250 руб.", ["100", "250"]],
    ["₽3255 и 3255₽", ["3255", "3255"]],
    ["₽ 3255 и 3255 ₽", ["3255", "3255"]],
    ["₽1\u202f500,50 и ₽-500", ["1500.5", "-500"]],
    ["Цена: ₽3255, доставка: ₽100.", ["3255", "100"]],
    ["abc₽3255 ₽3255abc ₽1,2.3 ₽1 50", []],
    ["https://x.test/₽3255 www.x.test/₽3255", []],
    ["₽1000000000001", []],
    ["1 500,50 руб.", ["1500.5"]],
    ["1,5 тыс. ₽", ["1500"]],
    ["2 млн рублей", ["2000000"]],
    ["500р", ["500"]],
    ["2026 г., 100 $, 100 €, 500", []],
    ["100 ₽ и снова 100 ₽", ["100", "100"]],
    ["🍊 1\u00a0500 ₽ и 1\u202f500 ₽", ["1500", "1500"]],
    ["1.000 ₽ и 1.000.000 ₽", ["1000", "1000000"]],
    ["1500.50 руб. -500 рублей", ["1500.5", "-500"]],
    ["2   тыс.   РУБЛЕЙ", ["2000"]],
    ["abc500р xyz 500рabc", []],
    ["https://x.test/500₽ www.x.test/200руб.", []],
    ["1 50 ₽ 1.00.0 ₽ 1,2.3 ₽ 100–200 ₽", []],
    ["+7 (900) 123-45-67 руб.", []],
    ["1000000000001 ₽", []],
    ["0,01 ₽", ["0.01"]],
  ])("%s", (text, expected) => expect(values(text)).toEqual(expected));
  it("preserves UTF-16 offsets and excludes Telegram code/pre entities", () => {
    const text = "🍊 500 ₽ и 600 ₽";
    expect(
      parseRubAmounts(text, [{ type: "code", offset: 3, length: 5 }]).map(
        (a) => [a.original, a.offset],
      ),
    ).toEqual([["600 ₽", 11]]);
    expect(
      parseRubAmounts(text, [{ type: "pre", offset: 0, length: text.length }]),
    ).toEqual([]);
  });
  it("retains amounts split by styling entities", () =>
    expect(
      parseRubAmounts("1 500 ₽", [{ type: "bold", offset: 0, length: 1 }]),
    ).toHaveLength(1));
  it("preserves prefix offsets and excludes Telegram code entities", () => {
    const text = "🍊 ₽3255 и 3255₽";
    expect(parseRubAmounts(text).map((a) => [a.original, a.offset])).toEqual([
      ["₽3255", 3],
      ["3255₽", 11],
    ]);
    expect(
      parseRubAmounts(text, [{ type: "code", offset: 3, length: 5 }]).map(
        (a) => a.original,
      ),
    ).toEqual(["3255₽"]);
  });
  it("limits input and output", () => {
    expect(values("x".repeat(20000) + "500 ₽")).toEqual([]);
    expect(values("1 ₽ ".repeat(500))).toHaveLength(6);
    expect(values("9".repeat(10000) + " ₽")).toEqual([]);
  });
});

